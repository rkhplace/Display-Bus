bool runCipherSelfTest() {
  DisplayConfig cfg;
  uint64_t ts = 0;
  const PacketError err = decodePacket(kTestPacket, sizeof(kTestPacket), kTestKey, cfg, ts);

  const bool ok = err == PacketError::None &&
                  strcmp(cfg.route, "B1 \xE2\x80\xA2 Bandung - Garut") == 0 && cfg.pergi &&
                  cfg.animation == Animation::ScrollLeft && cfg.speed == 50 &&
                  cfg.brightness == 80 && cfg.fontSize == 16 && ts > 0;

  Serial.printf("[SELFTEST] dekripsi paket contoh dari aplikasi: %s\n", ok ? "LULUS" : "GAGAL");
  return ok;
}
